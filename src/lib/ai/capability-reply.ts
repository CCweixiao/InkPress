/**
 * 本地快速短路（route.ts 在启动 Claude Agent 前先判一次，命中即直接回执，省 LLM 调用）。
 *
 * 两类零成本短路：
 * 1. 能力/身份介绍类询问（你能做什么 / 帮助 / 你是谁）→ 精简确定的能力清单。
 * 2. 误触/乱码输入（纯符号、空内容）→ 反问引导补充，不硬猜。
 *
 * 精度策略：整句命中（去礼貌语/语气词后 ^...$ 锚定）+ 长度判定，
 * 只拦确定的高频情形；长尾与含糊输入交给路由器 LLM（它会走 clarify 反问）。
 */

const POLITENESS =
  /^(你好|您好|哈喽|嗨|在吗|请问|hi|hello|hey|哟|哎呀)[，,。!！~、\s]*/i;
const TRIM_CHARS = /[？?。!！~，,、\s啊呀呢吧哟咯哈哒]+/g;

const CAPABILITY_PATTERNS = [
  // 你能做什么 / 你能干啥 / 你可以做哪些 / 你会搞什么
  /^(你|您)?(能|可以|会)(做|干|搞)(什么|啥|嘛|哪些)(事|的|功能|工作|活)?$/,
  // 你能帮什么忙
  /^(你|您)?(能|可以|会)帮(什么|啥|嘛)(忙|事|的)?$/,
  // 你的功能 / 能力有哪些 / 作用是什么
  /^(你|您)?(的)?(功能|能力|作用)(是什么|是啥|有哪些|有啥)?$/,
  // 有哪些功能 / 都有哪些能力
  /^(都)?有哪些?(功能|能力|作用)$/,
  // 功能介绍 / 能力说明
  /^(功能|能力)(介绍|说明|列表)$/,
  // 介绍你自己 / 介绍一下你
  /^介绍(一下)?(下)?(你|您)?(自己)?$/,
  // 你是谁 / 你是什么 / 你是干嘛的
  /^(你|您)?(是谁|是什么|叫什么|叫啥|是干嘛的|是做什么的|是啥)$/,
  // help / 帮助
  /^(help|帮助|帮帮忙|帮忙)$/,
];

/**
 * 判断输入是否为「能力/身份介绍」类纯询问。
 * 整句命中（去礼貌语/首尾语气词后 ^...$），且长度 ≤ 24，确保只拦纯元问题。
 */
export function isCapabilityQuestion(raw: string): boolean {
  if (!raw) return false;
  const text = raw
    .trim()
    .toLowerCase()
    .replace(POLITENESS, "")
    .replace(TRIM_CHARS, "");
  if (!text || text.length > 24) return false;
  return CAPABILITY_PATTERNS.some((re) => re.test(text));
}

/**
 * 能力清单（精简、确定）。命中能力询问时直接回这段，不走 Agent。
 * 顺带提示斜杠命令（/clear /skill），与新交互呼应。
 */
