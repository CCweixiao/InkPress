/**
 * 名称字符集：用于空间名等需要限制的标识符（成为目录名）。
 *
 * 允许：中英文、数字、空格、下划线、连字符、竖线（| ｜）、括号（() （））、
 * 尖括号（<>）、书名号（《》）、常见标点（， . 、 ·）与符号（& + ! ? : ： =）。
 *
 * 安全说明：Prisma 全程参数化查询，已杜绝 SQL 注入；前端渲染由 React 自动转义，
 * 尖括号 / 引号不会引发 XSS。
 */
const NAME_CHARS =
  "\\u4e00-\\u9fa5A-Za-z0-9 _\\-|｜()（）<>《》，.、·&+!?:：=";

/** 空间名称：必填非空，允许上述字符集 */
export const NAME_REGEX = new RegExp(`^[${NAME_CHARS}]+$`);

/**
 * 文章标题：允许所有可打印字符（含 emoji / 引号 / 标点 / #  等），
 * 仅禁止换行符与控制字符，避免破坏 UI 显示。
 *
 * 此前使用白名单枚举，导致 #" ' — … / 等常见字符被拒、保存失败。
 * 改为黑名单模式：用户输入的可见字符一律放行。
 */
export const TITLE_REGEX = /^[^\n\r\x00-\x1f\x7f]*$/;
