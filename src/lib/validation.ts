/**
 * 名称（空间名 / 文章标题）允许的字符集。
 *
 * 允许：中英文、数字、空格、下划线、连字符、竖线（| ｜）、括号（() （））、
 * 尖括号（<>）、书名号（《》）、常见标点（， . 、 ·）与符号（& + ! ? : ： =）。
 *
 * 安全说明：Prisma 全程参数化查询，已杜绝 SQL 注入；前端渲染由 React 自动转义，
 * 尖括号 / 引号不会引发 XSS。此处限制仅用于规范显示、排除控制字符与换行符。
 * 需要新增字符时，扩展 NAME_CHARS 即可。
 */
const NAME_CHARS =
  "\\u4e00-\\u9fa5A-Za-z0-9 _\\-|｜()（）<>《》，.、·&+!?:：=";

/** 空间名称：必填非空，允许上述字符集 */
export const NAME_REGEX = new RegExp(`^[${NAME_CHARS}]+$`);

/** 文章标题：允许空串（创建时空标题回落默认），允许上述字符集 */
export const TITLE_REGEX = new RegExp(`^[${NAME_CHARS}]*$`);
